import json
from statistics import quantiles
from typing import Any

from sqlalchemy import select
from sqlalchemy.ext.asyncio import AsyncSession

from app.models.evaluation import EvaluationRun
from app.models.evaluation_result import EvaluationResult
from app.models.model import Model
from app.schemas.evaluation.summary import EvaluationRunFinalFeedbackResponse
from app.services.evaluation_engine.cost import EvaluationCostService
from app.services.model_gateway import ModelGateway


class EvaluationRunSummaryService:
    """
    Aggregates evaluation results into a run-level summary.

    Quantitative scores are calculated deterministically from persisted
    EvaluationResult records.

    Final qualitative feedback can optionally be generated by an LLM
    using:
        - already-calculated overall score
        - already-calculated metric scores
        - run performance information
        - final rolling reducer feedback

    Metric scores are never recalculated by the LLM.

    Metric applicability is tracked independently from metric scores:

        applicable      -> contributes to metric average
        not_applicable  -> excluded from metric average
        failed          -> execution failure, excluded from metric average

    Case-level N/A is tracked separately from completed cases:

        case-level N/A -> no selected evaluator was applicable
        completed      -> at least one selected evaluator was executed

    N/A is never interpreted as a zero score.
    """

    @staticmethod
    def _is_case_not_applicable(
        result: EvaluationResult,
    ) -> bool:
        """Return True when the entire evaluation case was not applicable."""

        if result.status != "completed":
            return False

        scores = result.scores or {}

        if not isinstance(scores, dict):
            return False

        overall = scores.get("overall")

        return isinstance(overall, dict) and overall.get("status") == "not_applicable"

    @staticmethod
    async def calculate(
        db: AsyncSession,
        evaluation_run_id,
    ) -> dict[str, Any]:
        run_result = await db.execute(
            select(EvaluationRun).where(
                EvaluationRun.id == evaluation_run_id,
                EvaluationRun.is_active.is_(True),
            )
        )

        run = run_result.scalar_one_or_none()

        if run is None:
            return {
                "overall_score": 0.0,
                "metrics": {},
                "metric_applicability": {},
                "total_results": 0,
                "completed_cases": 0,
                "failed_cases": 0,
                "not_applicable_cases": 0,
                "feedback": {
                    "overall": "No evaluation results are available.",
                    "strengths": [],
                    "weaknesses": [],
                    "patterns": [],
                    "recommendations": [],
                    "evaluator_feedback": [],
                },
                "model": None,
                "performance": {
                    "duration_ms": None,
                    "total_model_latency_ms": 0,
                    "avg_model_latency_ms": None,
                    "min_model_latency_ms": None,
                    "p50_model_latency_ms": None,
                    "p95_model_latency_ms": None,
                    "p99_model_latency_ms": None,
                    "max_model_latency_ms": None,
                    "input_tokens": 0,
                    "output_tokens": 0,
                    "total_tokens": 0,
                    "throughput_cases_per_second": None,
                    "cost": EvaluationCostService.calculate(
                        input_tokens=0,
                        output_tokens=0,
                    ),
                    "total_results": 0,
                    "completed_cases": 0,
                    "failed_cases": 0,
                    "not_applicable_cases": 0,
                },
            }

        # --------------------------------------------------------------
        # Model pricing
        # --------------------------------------------------------------

        model_result = await db.execute(
            select(Model).where(
                Model.id == run.model_id,
                Model.is_active.is_(True),
            )
        )

        model = model_result.scalar_one_or_none()

        model_summary = None

        if model is not None:
            model_summary = {
                "id": model.id,
                "name": model.name,
                "provider": model.provider,
                "model_identifier": model.model_identifier,
            }

        input_price_per_million = model.input_price_per_million if model else 0.0

        output_price_per_million = model.output_price_per_million if model else 0.0

        pricing_currency = (
            model.pricing_currency if model else EvaluationCostService.DEFAULT_CURRENCY
        )

        # --------------------------------------------------------------
        # Evaluation results
        # --------------------------------------------------------------

        result = await db.execute(
            select(EvaluationResult).where(
                EvaluationResult.evaluation_run_id == evaluation_run_id,
                EvaluationResult.is_active.is_(True),
            )
        )

        results = result.scalars().all()

        case_not_applicable_results = [
            item for item in results if EvaluationRunSummaryService._is_case_not_applicable(item)
        ]

        completed_results = [
            item
            for item in results
            if item.status == "completed"
            and not EvaluationRunSummaryService._is_case_not_applicable(item)
        ]

        failed_results = [item for item in results if item.status == "failed"]

        not_applicable_cases = len(case_not_applicable_results)

        # --------------------------------------------------------------
        # Discover persisted metrics
        #
        # We discover metric names first so failed cases can be reflected
        # in applicability statistics for metrics that are known from the
        # run's persisted results.
        # --------------------------------------------------------------

        metric_names: set[str] = set()

        for result in results:
            scores = result.scores or {}

            if not isinstance(scores, dict):
                continue

            for metric_name in scores:
                if metric_name != "overall":
                    metric_names.add(metric_name)

        # --------------------------------------------------------------
        # Evaluation metrics + metric applicability
        # --------------------------------------------------------------

        metric_totals: dict[str, float] = {}
        metric_counts: dict[str, int] = {}

        metric_applicability: dict[str, dict[str, int]] = {
            metric_name: {
                "total": len(results),
                "applicable": 0,
                "not_applicable": 0,
                "failed": 0,
            }
            for metric_name in metric_names
        }

        overall_total = 0.0
        overall_count = 0

        for result in results:
            scores = result.scores or {}

            if not isinstance(scores, dict):
                scores = {}

            # ----------------------------------------------------------
            # Failed case
            #
            # A failed case has no metric-level execution result, so
            # every known metric is counted as failed for this case.
            # ----------------------------------------------------------

            if result.status == "failed":
                for metric_name in metric_names:
                    metric_applicability[metric_name]["failed"] += 1

                continue

            # ----------------------------------------------------------
            # Completed / case-level N/A result
            # ----------------------------------------------------------

            if result.status != "completed":
                continue

            # A case-level N/A result is not an executed case.
            #
            # Its individual evaluator scores are already persisted as
            # not_applicable, so metric applicability below will record
            # those metrics as N/A.
            #
            # It must not contribute to overall numeric scoring.
            # ----------------------------------------------------------

            if EvaluationRunSummaryService._is_case_not_applicable(result):
                for metric_name in metric_names:
                    metric_data = scores.get(metric_name)

                    if (
                        isinstance(metric_data, dict)
                        and metric_data.get("status") == "not_applicable"
                    ):
                        metric_applicability[metric_name]["not_applicable"] += 1

                continue

            # ----------------------------------------------------------
            # Completed case
            # ----------------------------------------------------------

            for metric_name in metric_names:
                metric_data = scores.get(metric_name)

                if not isinstance(metric_data, dict):
                    continue

                metric_status = metric_data.get("status")

                # ------------------------------------------------------
                # Explicitly persisted N/A
                # ------------------------------------------------------

                if metric_status == "not_applicable":
                    metric_applicability[metric_name]["not_applicable"] += 1
                    continue

                # ------------------------------------------------------
                # Completed metric
                #
                # Backward compatibility:
                # older persisted results may not have a "status"
                # field, but a numeric score still represents an
                # applicable metric result.
                # ------------------------------------------------------

                score = metric_data.get("score")

                if isinstance(score, bool):
                    continue

                if not isinstance(score, (int, float)):
                    continue

                score = float(score)

                metric_applicability[metric_name]["applicable"] += 1

                metric_totals[metric_name] = metric_totals.get(metric_name, 0.0) + score

                metric_counts[metric_name] = metric_counts.get(metric_name, 0) + 1

            # ----------------------------------------------------------
            # Overall score
            #
            # Only numeric overall scores contribute.
            # Case-level N/A was already excluded above.
            # ----------------------------------------------------------

            overall_data = scores.get("overall")

            if not isinstance(overall_data, dict):
                continue

            overall_score = overall_data.get("score")

            if isinstance(overall_score, bool):
                continue

            if not isinstance(overall_score, (int, float)):
                continue

            overall_total += float(overall_score)
            overall_count += 1

        metrics = {
            metric_name: metric_totals[metric_name] / metric_counts[metric_name]
            for metric_name in metric_totals
            if metric_counts[metric_name] > 0
        }

        # --------------------------------------------------------------
        # Applicability coverage
        # --------------------------------------------------------------

        metric_applicability_summary: dict[str, dict[str, Any]] = {}

        for metric_name, counts in metric_applicability.items():
            total = counts["total"]
            applicable = counts["applicable"]

            coverage = applicable / total if total > 0 else 0.0

            metric_applicability_summary[metric_name] = {
                "total": total,
                "applicable": applicable,
                "not_applicable": counts["not_applicable"],
                "failed": counts["failed"],
                "coverage": coverage,
            }

        # --------------------------------------------------------------
        # Overall score
        #
        # None means there was no applicable overall score.
        # This is semantically different from an actual score of 0.0.
        # --------------------------------------------------------------

        overall_score = overall_total / overall_count if overall_count > 0 else None

        # --------------------------------------------------------------
        # Deterministic fallback feedback
        # --------------------------------------------------------------

        feedback = EvaluationRunSummaryService._build_feedback(
            metrics=metrics,
            completed_results=completed_results,
            overall_score=overall_score,
            metric_applicability=metric_applicability_summary,
        )

        # --------------------------------------------------------------
        # Run-level performance metrics
        # --------------------------------------------------------------

        latencies = [
            result.latency_ms for result in completed_results if result.latency_ms is not None
        ]

        total_model_latency_ms = sum(latencies)

        avg_model_latency_ms = total_model_latency_ms / len(latencies) if latencies else None

        min_model_latency_ms = min(latencies) if latencies else None

        max_model_latency_ms = max(latencies) if latencies else None

        p50_model_latency_ms = None
        p95_model_latency_ms = None
        p99_model_latency_ms = None

        if latencies:
            if len(latencies) == 1:
                p50_model_latency_ms = float(latencies[0])
                p95_model_latency_ms = float(latencies[0])
                p99_model_latency_ms = float(latencies[0])
            else:
                percentile_values = quantiles(
                    latencies,
                    n=100,
                    method="inclusive",
                )

                p50_model_latency_ms = percentile_values[49]
                p95_model_latency_ms = percentile_values[94]
                p99_model_latency_ms = percentile_values[98]

        input_tokens = sum(result.input_tokens or 0 for result in completed_results)

        output_tokens = sum(result.output_tokens or 0 for result in completed_results)

        total_tokens = sum(result.total_tokens or 0 for result in completed_results)

        # --------------------------------------------------------------
        # Cost
        # --------------------------------------------------------------

        cost = EvaluationCostService.calculate(
            input_tokens=input_tokens,
            output_tokens=output_tokens,
            input_price_per_million=input_price_per_million,
            output_price_per_million=output_price_per_million,
            currency=pricing_currency,
        )

        # --------------------------------------------------------------
        # Throughput
        # --------------------------------------------------------------

        throughput_cases_per_second = None

        if run.duration_ms and run.duration_ms > 0:
            throughput_cases_per_second = len(completed_results) / (run.duration_ms / 1000)

        performance = {
            "duration_ms": run.duration_ms,
            "total_model_latency_ms": total_model_latency_ms,
            "avg_model_latency_ms": avg_model_latency_ms,
            "min_model_latency_ms": min_model_latency_ms,
            "p50_model_latency_ms": p50_model_latency_ms,
            "p95_model_latency_ms": p95_model_latency_ms,
            "p99_model_latency_ms": p99_model_latency_ms,
            "max_model_latency_ms": max_model_latency_ms,
            "input_tokens": input_tokens,
            "output_tokens": output_tokens,
            "total_tokens": total_tokens,
            "throughput_cases_per_second": throughput_cases_per_second,
            "cost": cost,
            "total_results": len(results),
            "completed_cases": len(completed_results),
            "failed_cases": len(failed_results),
            "not_applicable_cases": not_applicable_cases,
        }

        return {
            "model": model_summary,
            "overall_score": overall_score,
            "metrics": metrics,
            "metric_applicability": metric_applicability_summary,
            "total_results": len(results),
            "completed_cases": len(completed_results),
            "failed_cases": len(failed_results),
            "not_applicable_cases": not_applicable_cases,
            "feedback": feedback,
            "performance": performance,
            "metadata": {
                "model": (
                    {
                        **model_summary,
                        "id": str(model_summary["id"]),
                    }
                    if model_summary is not None
                    else None
                ),
            },
        }

    # ------------------------------------------------------------------
    # Final qualitative summary
    # ------------------------------------------------------------------

    @staticmethod
    async def generate_final_feedback(
        *,
        model_gateway: ModelGateway,
        evaluation_run_id,
        overall_score: float | None,
        metrics: dict[str, float],
        performance: dict[str, Any],
        rolling_feedback: dict[str, Any] | None,
        model: str,
        timeout: float = 60.0,
        base_url: str | None = None,
    ) -> dict[str, Any]:
        """
        Generate the final qualitative summary.

        The supplied scores and performance metrics are authoritative.
        The LLM only interprets them and produces qualitative feedback.

        Rolling feedback is treated as compressed qualitative evidence.
        """

        prompt = EvaluationRunSummaryService._build_final_feedback_prompt(
            evaluation_run_id=evaluation_run_id,
            overall_score=overall_score,
            metrics=metrics,
            performance=performance,
            rolling_feedback=rolling_feedback,
        )

        configuration: dict[str, Any] = {
            "model": model,
            "timeout": timeout,
            "response_format": "json",
        }

        if base_url is not None:
            configuration["base_url"] = base_url

        response = await model_gateway.generate(
            prompt=prompt,
            configuration=configuration,
        )

        return EvaluationRunSummaryService._parse_final_feedback(
            response.output,
        )

    @staticmethod
    def _build_final_feedback_prompt(
        *,
        evaluation_run_id,
        overall_score: float | None,
        metrics: dict[str, float],
        performance: dict[str, Any],
        rolling_feedback: dict[str, Any] | None,
    ) -> str:
        metrics_json = json.dumps(
            metrics,
            ensure_ascii=False,
            indent=2,
        )

        performance_json = json.dumps(
            performance,
            ensure_ascii=False,
            indent=2,
            default=str,
        )

        rolling_feedback_json = json.dumps(
            rolling_feedback or {},
            ensure_ascii=False,
            indent=2,
        )

        formatted_overall_score = f"{overall_score:.6f}" if overall_score is not None else "N/A"

        return f"""
You are the final qualitative analysis judge for an AI evaluation platform.

Your responsibility is to synthesize the evaluation evidence into a concise,
useful final summary.

IMPORTANT:

The numerical scores below have already been calculated by the evaluation
platform and are authoritative.

DO NOT recalculate, modify, reinterpret numerically, or invent any scores.

Use ALL provided metrics when forming the overall assessment.

Evaluation run:
{evaluation_run_id}

Overall score:
{formatted_overall_score}

Metrics:
{metrics_json}

Performance:
{performance_json}

Final rolling feedback:
{rolling_feedback_json}

The rolling feedback is already a compressed summary of case-level evaluator
feedback. Use it as qualitative evidence, but do not blindly copy it.

If the overall score is N/A, explicitly recognize that no applicable overall
score was available. Do not interpret N/A as zero or poor performance.

Generate ONLY valid JSON with exactly this structure:

{{
  "overall": "concise overall assessment",
  "strengths": [
    "strength 1",
    "strength 2",
    "strength 3"
  ],
  "weaknesses": [
    "weakness 1",
    "weakness 2",
    "weakness 3"
  ],
  "patterns": [
    "pattern 1",
    "pattern 2",
    "pattern 3"
  ],
  "recommendations": [
    "recommendation 1",
    "recommendation 2",
    "recommendation 3"
  ],
  "evaluator_feedback": []
}}

Rules:

1. Use ALL metric scores when forming the overall assessment.
2. Treat the supplied overall score as authoritative.
3. Never invent metric values.
4. Never recalculate the overall score.
5. Treat N/A as unavailable applicability, not as a zero score.
6. Strengths must contain at least 3 evidence-grounded observations.
7. Weaknesses must contain at least 3 evidence-grounded observations.
8. Patterns must contain at least 3 recurring or cross-case observations.
9. Recommendations must contain at least 3 actionable recommendations.
10. Consider performance information such as completion, failure, and
    not-applicable counts when it provides meaningful evidence.
11. Do not manufacture praise or criticism unsupported by the supplied evidence.
12. When evidence is limited, make conservative evidence-based observations.
13. evaluator_feedback may remain an empty list.
14. Return JSON only.
""".strip()

    @staticmethod
    def _parse_final_feedback(
        raw_output: str,
    ) -> dict[str, Any]:
        if not raw_output or not raw_output.strip():
            raise ValueError("Final summary LLM returned an empty response.")

        cleaned = raw_output.strip()

        if cleaned.startswith("```"):
            lines = cleaned.splitlines()

            if lines and lines[0].strip().startswith("```"):
                lines = lines[1:]

            if lines and lines[-1].strip() == "```":
                lines = lines[:-1]

            cleaned = "\n".join(lines).strip()

            if cleaned.lower().startswith("json"):
                cleaned = cleaned[4:].strip()

        try:
            data = json.loads(cleaned)
        except json.JSONDecodeError as exc:
            raise ValueError("Final summary LLM returned invalid JSON.") from exc

        if not isinstance(data, dict):
            raise ValueError("Final summary LLM response must be a JSON object.")

        feedback = EvaluationRunFinalFeedbackResponse.model_validate(data)

        return feedback.model_dump()

    @staticmethod
    def _build_final_fallback_feedback(
        *,
        overall_score: float | None,
        metrics: dict[str, float],
        performance: dict[str, Any],
        completed_cases: int,
        failed_cases: int,
        rolling_feedback: dict[str, Any] | None,
        metric_applicability: dict[str, dict[str, Any]] | None = None,
    ) -> dict[str, Any]:
        """
        Build a schema-valid final feedback object when final LLM
        synthesis is unavailable or invalid.

        This method does not calculate or modify evaluation scores.
        It only turns already-computed evidence into qualitative
        observations.
        """

        strengths: list[str] = []
        weaknesses: list[str] = []
        patterns: list[str] = []
        recommendations: list[str] = []

        # --------------------------------------------------------------
        # Metric observations
        # --------------------------------------------------------------

        sorted_metrics = sorted(
            metrics.items(),
            key=lambda item: item[1],
            reverse=True,
        )

        if sorted_metrics:
            strongest_metric, strongest_score = sorted_metrics[0]

            strengths.append(
                (
                    f"{strongest_metric} is the strongest measured metric "
                    f"with a score of {strongest_score:.4f}."
                )
            )

        if len(sorted_metrics) >= 2:
            second_metric, second_score = sorted_metrics[1]

            strengths.append(
                (
                    f"{second_metric} also contributes measurable performance "
                    f"with a score of {second_score:.4f}."
                )
            )

        if metrics:
            strengths.append(
                (
                    f"The evaluation produced {len(metrics)} calculated "
                    "evaluation metrics for comparison."
                )
            )
        elif metric_applicability:
            strengths.append(
                (
                    "The evaluation recorded metric applicability information "
                    "even though no numeric metric score was available."
                )
            )
        else:
            strengths.append("The evaluation run produced persisted execution evidence.")

        # --------------------------------------------------------------
        # Applicability observations
        # --------------------------------------------------------------

        if metric_applicability:
            na_metrics = [
                metric_name
                for metric_name, statistics in metric_applicability.items()
                if statistics.get("not_applicable", 0) > 0
            ]

            if na_metrics:
                patterns.append(
                    (
                        "Some evaluation metrics were not applicable to "
                        f"all cases: {', '.join(sorted(na_metrics))}."
                    )
                )

        # --------------------------------------------------------------
        # Weaknesses
        # --------------------------------------------------------------

        if sorted_metrics:
            weakest_metric, weakest_score = sorted_metrics[-1]

            weaknesses.append(
                (
                    f"{weakest_metric} is the lowest measured metric "
                    f"with a score of {weakest_score:.4f}."
                )
            )

        if failed_cases > 0:
            weaknesses.append(
                (
                    f"{failed_cases} evaluation case(s) failed during the run, "
                    "reducing complete evaluation coverage."
                )
            )
        else:
            weaknesses.append("No evaluation cases failed during execution.")

        score_spread = None

        if len(metrics) >= 2:
            scores = list(metrics.values())
            score_spread = max(scores) - min(scores)

        if score_spread is not None:
            weaknesses.append(
                (
                    f"The difference between the highest and lowest metric "
                    f"scores is {score_spread:.4f}, indicating uneven "
                    "performance across metrics."
                )
            )
        elif overall_score is None:
            weaknesses.append("No applicable overall score was available for this run.")
        else:
            weaknesses.append(
                "Only limited cross-metric variation is available for comparison in this run."
            )

        # --------------------------------------------------------------
        # Patterns
        # --------------------------------------------------------------

        if sorted_metrics:
            highest_metric, highest_score = sorted_metrics[0]

            patterns.append(
                (
                    f"{highest_metric} currently leads the measured "
                    f"evaluation metrics at {highest_score:.4f}."
                )
            )

        if sorted_metrics:
            lowest_metric, lowest_score = sorted_metrics[-1]

            patterns.append(
                (f"{lowest_metric} is currently the weakest measured metric at {lowest_score:.4f}.")
            )

        if completed_cases or failed_cases:
            patterns.append(
                (
                    f"The run processed {completed_cases} completed case(s) "
                    f"and {failed_cases} failed case(s)."
                )
            )
        else:
            patterns.append("The run contains limited execution-level evidence.")

        # --------------------------------------------------------------
        # Rolling reducer evidence
        # --------------------------------------------------------------

        if isinstance(rolling_feedback, dict):
            rolling_patterns = rolling_feedback.get(
                "patterns",
                [],
            )

            if isinstance(rolling_patterns, list):
                for pattern in rolling_patterns:
                    if (
                        isinstance(pattern, str)
                        and pattern.strip()
                        and pattern.strip() not in patterns
                        and len(patterns) < 3
                    ):
                        patterns.append(pattern.strip())

        # --------------------------------------------------------------
        # Recommendations
        # --------------------------------------------------------------

        if sorted_metrics:
            weakest_metric, weakest_score = sorted_metrics[-1]

            recommendations.append(
                (
                    f"Prioritize improving {weakest_metric}, currently "
                    f"the lowest measured metric at {weakest_score:.4f}."
                )
            )
        elif overall_score is None:
            recommendations.append(
                "Increase metric applicability coverage so future runs "
                "produce broader quantitative evidence."
            )
        else:
            recommendations.append("Continue collecting evaluation metrics across future runs.")

        if failed_cases > 0:
            recommendations.append(
                (
                    "Investigate failed evaluation cases to improve "
                    "execution reliability and evaluation coverage."
                )
            )
        else:
            recommendations.append("Continue monitoring evaluation execution reliability.")

        if len(metrics) >= 2:
            recommendations.append(
                (
                    "Track the metric distribution across future runs "
                    "to determine whether the weakest dimensions improve."
                )
            )
        elif metric_applicability:
            recommendations.append(
                (
                    "Review metric applicability coverage and add "
                    "complementary metrics where appropriate."
                )
            )
        else:
            recommendations.append(
                "Add complementary evaluation metrics to obtain broader quality coverage."
            )

        # --------------------------------------------------------------
        # Use rolling feedback where useful
        # --------------------------------------------------------------

        if isinstance(rolling_feedback, dict):
            rolling_recommendations = rolling_feedback.get(
                "recommendations",
                [],
            )

            if isinstance(rolling_recommendations, list):
                for recommendation in rolling_recommendations:
                    if (
                        isinstance(recommendation, str)
                        and recommendation.strip()
                        and recommendation.strip() not in recommendations
                        and len(recommendations) < 3
                    ):
                        recommendations.append(recommendation.strip())

        # --------------------------------------------------------------
        # Ensure exact minimum contract
        # --------------------------------------------------------------

        while len(strengths) < 3:
            strengths.append(
                "The run contains persisted evaluation evidence that can be "
                "used for comparison across future runs."
            )

        while len(weaknesses) < 3:
            weaknesses.append(
                "Additional evaluation evidence can help identify further "
                "quality gaps across cases."
            )

        while len(patterns) < 3:
            patterns.append(
                "Metric and execution results should be compared across future evaluation runs."
            )

        while len(recommendations) < 3:
            recommendations.append(
                "Continue monitoring evaluation quality and execution "
                "reliability over subsequent runs."
            )

        # --------------------------------------------------------------
        # Overall assessment
        # --------------------------------------------------------------

        if overall_score is None:
            overall = (
                "No applicable overall evaluation score was available for "
                "this run. Metric applicability should be considered when "
                "interpreting the evaluation evidence."
            )
        elif overall_score >= 0.8:
            overall = (
                f"Strong overall evaluation performance with an overall "
                f"score of {overall_score:.4f}."
            )
        elif overall_score >= 0.6:
            overall = (
                f"Moderate overall evaluation performance with an overall "
                f"score of {overall_score:.4f} and some areas for improvement."
            )
        elif overall_score >= 0.4:
            overall = (
                f"Below-average overall evaluation performance with an "
                f"overall score of {overall_score:.4f}."
            )
        else:
            overall = (
                f"Poor overall evaluation performance with an overall score of {overall_score:.4f}."
            )

        return {
            "overall": overall,
            "strengths": strengths[:3],
            "weaknesses": weaknesses[:3],
            "patterns": patterns[:3],
            "recommendations": recommendations[:3],
            "evaluator_feedback": [],
        }

    # ------------------------------------------------------------------
    # Existing deterministic feedback
    # ------------------------------------------------------------------

    @staticmethod
    def _build_feedback(
        metrics: dict[str, float],
        completed_results: list[EvaluationResult],
        overall_score: float | None = None,
        metric_applicability: dict[str, dict[str, Any]] | None = None,
    ) -> dict[str, Any]:
        strengths: list[str] = []
        weaknesses: list[str] = []
        recommendations: list[str] = []
        patterns: list[str] = []
        evaluator_feedback: list[str] = []

        for result in completed_results:
            if not result.feedback:
                continue

            feedback_text = result.feedback.strip()

            if not feedback_text:
                continue

            evaluator_feedback.append(feedback_text)

        evaluator_feedback = evaluator_feedback[:10]

        relevance = metrics.get("relevance")

        if relevance is not None:
            if relevance >= 0.8:
                strengths.append("High relevance to the evaluation context.")
            elif relevance < 0.5:
                weaknesses.append(
                    "Low relevance indicates that responses may not stay "
                    "focused on the provided context or question."
                )
                recommendations.append(
                    "Improve response relevance by focusing more directly "
                    "on the question and supporting context."
                )
            else:
                weaknesses.append("Relevance is acceptable but has room for improvement.")
                recommendations.append(
                    "Keep responses more directly aligned with the question and supporting context."
                )

        faithfulness = metrics.get("faithfulness")

        if faithfulness is not None:
            if faithfulness >= 0.8:
                strengths.append(
                    "Strong faithfulness indicates good grounding in the provided context."
                )
            elif faithfulness < 0.7:
                weaknesses.append(
                    "Faithfulness can be improved because some response "
                    "content is not sufficiently supported by the context."
                )
                recommendations.append(
                    "Improve grounding by limiting unsupported claims "
                    "and relying more closely on the provided context."
                )
            else:
                weaknesses.append("Faithfulness is acceptable but could be improved.")

        f1 = metrics.get("f1")

        if f1 is not None:
            if f1 >= 0.8:
                strengths.append(
                    "High F1 indicates strong token-level similarity to reference answers."
                )
            elif f1 < 0.4:
                weaknesses.append(
                    "Low F1 indicates substantial mismatch with the reference answers."
                )
                recommendations.append(
                    "Improve alignment with expected answers while preserving relevant information."
                )
            else:
                weaknesses.append("F1 shows moderate alignment with reference answers.")

        exact_match = metrics.get("exact_match")

        if exact_match is not None:
            if exact_match >= 0.8:
                strengths.append(
                    "High exact-match performance indicates strong agreement with expected answers."
                )
            elif exact_match < 0.5:
                weaknesses.append(
                    "Low exact-match performance indicates responses "
                    "frequently differ from expected answers."
                )

        contains = metrics.get("contains")

        if contains is not None:
            if contains >= 0.8:
                strengths.append("Responses generally contain the expected answer content.")
            elif contains < 0.5:
                weaknesses.append("Responses frequently omit expected answer content.")
                recommendations.append(
                    "Ensure responses contain the key information "
                    "expected by the evaluation dataset."
                )

        llm_judge = metrics.get("llm_judge")

        if llm_judge is not None:
            if llm_judge >= 0.8:
                strengths.append("LLM judge evaluation indicates strong overall response quality.")
            elif llm_judge < 0.5:
                weaknesses.append("LLM judge evaluation indicates significant quality issues.")
                recommendations.append(
                    "Review judge feedback and improve correctness, "
                    "relevance, completeness, and clarity."
                )
            else:
                weaknesses.append(
                    "LLM judge evaluation indicates acceptable but improvable response quality."
                )
                recommendations.append(
                    "Review judge feedback and improve completeness, "
                    "clarity, relevance, and grounding."
                )

        # --------------------------------------------------------------
        # Applicability observations
        # --------------------------------------------------------------

        if metric_applicability:
            not_applicable_metrics = [
                (
                    metric_name,
                    statistics.get("not_applicable", 0),
                    statistics.get("total", 0),
                )
                for metric_name, statistics in metric_applicability.items()
                if statistics.get("not_applicable", 0) > 0
            ]

            if not_applicable_metrics:
                for (
                    metric_name,
                    not_applicable_count,
                    total,
                ) in not_applicable_metrics:
                    coverage = metric_applicability[metric_name].get(
                        "coverage",
                        0.0,
                    )

                    patterns.append(
                        (
                            f"{metric_name} was not applicable to "
                            f"{not_applicable_count} of {total} case(s), "
                            f"with {coverage:.2%} applicability coverage."
                        )
                    )

        # --------------------------------------------------------------
        # Overall assessment
        #
        # Use the authoritative score supplied by calculate().
        # Never recompute it from metric averages here.
        # --------------------------------------------------------------

        if overall_score is None:
            overall = "No applicable overall evaluation score was available for this run."
        elif overall_score >= 0.8:
            overall = "Strong overall evaluation performance."
        elif overall_score >= 0.6:
            overall = "Moderate overall evaluation performance with some areas for improvement."
        elif overall_score >= 0.4:
            overall = (
                "Below-average evaluation performance with several areas requiring improvement."
            )
        else:
            overall = "Poor overall evaluation performance requiring significant improvement."

        # --------------------------------------------------------------
        # Ensure deterministic feedback satisfies the public contract.
        # Every section must contain at least 3 items.
        # --------------------------------------------------------------

        if not strengths:
            if overall_score is None:
                strengths.append(
                    "The evaluation recorded execution evidence even "
                    "though no applicable overall score was available."
                )
            else:
                strengths.append("The evaluation produced measurable metric results.")

        if not weaknesses:
            weaknesses.append(
                "No major metric weaknesses were identified from the available evidence."
            )

        if not patterns:
            patterns.append(
                "Metric performance should be interpreted across completed evaluation cases."
            )

        if not recommendations:
            recommendations.append("Continue monitoring evaluation metrics across future runs.")

        strengths = EvaluationRunSummaryService._ensure_minimum_feedback_items(
            strengths,
            defaults=[
                "The evaluation produced measurable metric results.",
                "Completed cases provide evidence for model performance.",
                "The run completed with persisted evaluation results.",
            ],
        )

        weaknesses = EvaluationRunSummaryService._ensure_minimum_feedback_items(
            weaknesses,
            defaults=[
                "Some metric areas may require further improvement.",
                "Performance should be reviewed across individual evaluation cases.",
                "Failed cases can affect the overall evaluation outcome.",
            ],
        )

        patterns = EvaluationRunSummaryService._ensure_minimum_feedback_items(
            patterns,
            defaults=[
                "Metric performance varies across evaluation dimensions.",
                "Completed, failed, and not-applicable cases should be "
                "considered when interpreting the run.",
                "Case-level evaluator feedback provides additional evidence "
                "for recurring behavior.",
            ],
        )

        recommendations = EvaluationRunSummaryService._ensure_minimum_feedback_items(
            recommendations,
            defaults=[
                "Continue monitoring evaluation metrics across future runs.",
                "Review low-scoring cases to identify recurring failure patterns.",
                "Investigate failed cases and improve model reliability.",
            ],
        )

        return {
            "overall": overall,
            "strengths": strengths,
            "weaknesses": weaknesses,
            "patterns": patterns,
            "recommendations": recommendations,
            "evaluator_feedback": evaluator_feedback,
        }

    @staticmethod
    def _ensure_minimum_feedback_items(
        items: list[str],
        *,
        defaults: list[str],
        minimum: int = 3,
    ) -> list[str]:
        """
        Ensure a feedback section contains at least `minimum` items.

        Existing evidence-based items are preserved. Defaults are used only
        when the available evidence does not produce enough items.
        """

        result = list(items)

        for default in defaults:
            if len(result) >= minimum:
                break

            if default not in result:
                result.append(default)

        while len(result) < minimum:
            result.append("Continue monitoring evaluation evidence across future runs.")

        return result
